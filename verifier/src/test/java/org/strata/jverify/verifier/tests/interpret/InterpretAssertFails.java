package org.strata.jverify.verifier.tests.interpret;

import org.strata.jverify.InterpretEntry;
import org.strata.jverify.testengine.JVerifyTest;

import static org.strata.jverify.JVerify.*;

/**
 * Discriminating test: this program PASSES under the SMT checker but FAILS
 * under the concrete interpreter, so it proves the harness really runs the
 * interpreter in {@code interpret = true} mode (and not a silent fallback to
 * SMT verification).
 *
 * <p>The mechanism is {@code precondition(false)}:
 * <ul>
 *   <li><b>SMT verification</b> assumes the precondition, which makes the path
 *       infeasible, so {@code check(false)} holds <i>vacuously</i> — exit 0.</li>
 *   <li><b>The interpreter</b> does not inject the precondition as a runtime
 *       guard on the executed entry point, so execution reaches and evaluates
 *       {@code check(false)}, which fails at the marked range — exit 4.</li>
 * </ul>
 *
 * Because this is run with {@code interpret = true} and expects {@code exitCode = 4},
 * it would fail if interpretation were ever replaced by SMT verification (which
 * would report exit 0). The entry point is found via the @InterpretEntry marker.
 */
@JVerifyTest(
        interpret = true,
        exitCode = 4,
        methodsVerified = 1,
        methodsInvalid = 1,
        errorCount = 1,
        skip = "This test currently fails because the interpreter " +
                "fails on `assume(false)` which is generated by the " +
                "precondition during the Contract pass. Waiting for " +
                "the change by Remy to land before we can activate it.")
class InterpretAssertFails {
    @InterpretEntry
    static void run() {
        precondition(false);
        check(false);
//      ^^^^^^^^^^^^ Error: assertion does not hold
    }
}
